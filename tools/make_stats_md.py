#!/usr/bin/env python3
"""Write docs/STATS.md (Mega Millions) and docs/POWERBALL-STATS.md (Powerball) from the
canonical data files using tools/reference.py. Stdlib only.

Usage: python3 tools/make_stats_md.py [--game megamillions|powerball|all]   (default all)
"""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import reference as R  # noqa: E402


def gammaq(a, x):
    """Regularized upper incomplete gamma Q(a, x) (Numerical Recipes series / continued fraction)."""
    if x <= 0:
        return 1.0
    gln = math.lgamma(a)
    if x < a + 1:
        ap, s, d = a, 1.0 / a, 1.0 / a
        for _ in range(1000):
            ap += 1
            d *= x / ap
            s += d
            if abs(d) < abs(s) * 1e-15:
                break
        return 1.0 - s * math.exp(-x + a * math.log(x) - gln)
    b = x + 1 - a
    c, d = 1e300, 1 / b
    h = d
    for i in range(1, 1000):
        an = -i * (i - a)
        b += 2
        d = an * d + b
        d = 1e-300 if abs(d) < 1e-300 else d
        c = b + an / c
        c = 1e-300 if abs(c) < 1e-300 else c
        d = 1 / d
        de = d * c
        h *= de
        if abs(de - 1) < 1e-15:
            break
    return math.exp(-x + a * math.log(x) - gln) * h


# per-game document settings (Mega Millions text is unchanged from the original MM-only script)
DOCS = {
    "megamillions": dict(
        title="Mega Millions draw statistics (current matrix)",
        data="draws.csv", out="STATS.md", url="https://data.ny.gov/api/views/5xaw-6ayf/rows.csv?accessType=DOWNLOAD",
        golden="tests/golden/stats.txt", cli="mega-index guess", extra=""),
    "powerball": dict(
        title="Powerball draw statistics (current matrix)",
        data="powerball-draws.csv", out="POWERBALL-STATS.md",
        url="https://data.ny.gov/api/views/d6yy-54nr/rows.csv?accessType=DOWNLOAD",
        golden="tests/golden/pb_stats.txt", cli="mega-index guess --game powerball",
        extra=" Only the main draw is used; Double Play results are ignored."),
}


def main_game(g):
    cfg = DOCS[g.id]
    st = R.Stats(g, R.load_draws(os.path.join(ROOT, "data", cfg["data"]), g))
    D, k, K, B = st.D, g.white_count, g.white_max, g.bonus_max
    bn, total = g.bonus_name, R.group(g.total)
    ew, eb = D * k / K, D / B
    chiw = sum((st.wf[n] - ew) ** 2 / ew for n in st.whites())
    chib = sum((st.bf[n] - eb) ** 2 / eb for n in st.bonuses())
    pw, pb = gammaq((K - 1) / 2, chiw / 2), gammaq((B - 1) / 2, chib / 2)
    L = []
    a = L.append
    a("# %s" % cfg["title"])
    a("")
    a("> **Honest note.** Every draw is independent and every ticket is equally likely: "
      "**1 in %s**. Hot/cold/overdue analysis is for fun and cannot predict results. "
      "Weighted picks are not uniform, so plain uniform-random (`pick --mode uniform`) stays the default." % total)
    a("")
    a("Generated by `tools/make_stats_md.py` from `data/%s` (source: NY Open Data, "
      "`%s`). "
      "The exact CLI output for the same data is `%s`.%s" % (cfg["data"], cfg["url"], cfg["golden"], cfg["extra"]))
    a("")
    a("| Item | Value |")
    a("|---|---|")
    a("| Matrix | %d white balls of 1-%d + %s 1-%d (from %s) |" % (k, K, bn, B, g.matrix_start))
    a("| Draws | %d |" % D)
    a("| Date range | %s to %s |" % (st.draws[0][0], st.draws[-1][0]))
    a("| Expected hits per white ball | %d x %d / %d = %.2f |" % (D, k, K, ew))
    a("| Expected hits per %s | %d / %d = %.2f |" % (bn, D, B, eb))
    a("")
    a("\"Gap\" = draws since the number last appeared (0 = in the most recent draw; "
      "never drawn = %d). Rankings follow SPEC.md section 5." % D)
    a("")
    for title, pool, top in (("White balls", "w", 10), (bn, "b", 5)):
        f = st.wf if pool == "w" else st.bf
        gap = st.wgap if pool == "w" else st.bgap
        e = ew if pool == "w" else eb
        a("## %s" % title)
        a("")
        for kind, label in (("hot", "Hot (most drawn)"), ("cold", "Cold (least drawn)"),
                            ("overdue", "Overdue (longest gap)")):
            a("**%s, top %d**" % (label, top))
            a("")
            a("| Rank | Number | Freq | vs expected | Gap |")
            a("|---:|---:|---:|---:|---:|")
            for r, n in enumerate(st.rank(kind, pool)[:top], 1):
                a("| %d | %02d | %d | %+.2f | %d |" % (r, n, f[n], f[n] - e, gap[n]))
            a("")
    a("## Chi-square goodness of fit vs uniform")
    a("")
    a("| Pool | chi-square | df | p-value (approx.) |")
    a("|---|---:|---:|---:|")
    a("| White balls (%d ball draws over %d numbers) | %.2f | %d | %.3f |" % (D * k, K, chiw, K - 1, pw))
    a("| %s (%d draws over %d numbers) | %.2f | %d | %.3f |" % (bn, D, B, chib, B - 1, pb))
    a("")
    a("p-value = P(chi-square >= observed) under a fair, uniform draw, computed with the regularized "
      "upper incomplete gamma function Q(df/2, x/2). Note: the 5 whites in a draw are sampled without "
      "replacement, so the white-ball test is a close approximation, not exact.")
    a("")
    concl = []
    for nm, p in (("white balls", pw), ("%ss" % bn, pb)):
        concl.append("the %s give p = %.2f, %s" % (
            nm, p, "far above 0.05, so there is no evidence of bias" if p > 0.05
            else "below 0.05; with this few draws treat it as noise unless it persists"))
    a("**Plain-language conclusion:** %s; %s. The spread between \"hot\" and \"cold\" numbers is "
      "about what pure chance produces with %s%d draws (roughly %d hits per white ball and %d per "
      "%s). Nothing here suggests the draws are anything but uniform random."
      % (concl[0], concl[1], "only " if D < 500 else "", D, round(ew), round(eb), bn))
    a("")
    a("## The 3 deterministic guess tickets (`%s`)" % cfg["cli"])
    a("")
    a("| Play | Kind | Ticket | Index |")
    a("|---|---|---|---:|")
    for letter, (label, w, b, i) in zip("ABC", R.guess_tickets(st)):
        a("| %s | %s | %s | %s |" % (letter, label, R.fmt_ticket(g, w, b), R.group(i)))
    a("")
    a("- HOT = top 5 hot whites + top hot %s." % bn)
    a("- COLD = top 5 cold whites + top cold %s." % bn)
    a("- BALANCED = top 3 hot whites + the 2 most overdue whites not already chosen + the most overdue %s." % bn)
    a("")
    a("> These guesses have exactly the same odds as any other ticket: **1 in %s**. For fun only." % total)
    a("")
    with open(os.path.join(ROOT, "docs", cfg["out"]), "w", newline="\n") as fh:
        fh.write("\n".join(L))
    print("%s: chi white %.2f p=%.3f; chi %s %.2f p=%.3f" % (g.id, chiw, pw, g.bonus_abbr, chib, pb))


def main(argv):
    which = "all"
    if argv[:1] == ["--game"] and len(argv) == 2:
        which = argv[1]
    elif argv:
        print(__doc__)
        return 0 if argv[0] in ("-h", "--help") else 2
    games = {"megamillions": [R.MEGA_MILLIONS], "powerball": [R.POWERBALL],
             "all": [R.MEGA_MILLIONS, R.POWERBALL]}
    if which not in games:
        print("error: unknown game '%s'" % which, file=sys.stderr)
        return 2
    for g in games[which]:
        main_game(g)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
