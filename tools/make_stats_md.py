#!/usr/bin/env python3
"""Write docs/STATS.md from data/draws.csv using tools/reference.py. Stdlib only."""
import math
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import reference as R  # noqa: E402


def gammaq(a, x):
    """Regularized upper incomplete gamma Q(a, x) (Numerical Recipes series / continued fraction)."""
    if x <= 0:
        return 1.0
    gln = math.lgamma(a)
    if x < a + 1:
        ap, s, d = a, 1.0 / a, 1.0 / a
        for _ in range(1000):
            ap += 1
            d *= x / ap
            s += d
            if abs(d) < abs(s) * 1e-15:
                break
        return 1.0 - s * math.exp(-x + a * math.log(x) - gln)
    b = x + 1 - a
    c, d = 1e300, 1 / b
    h = d
    for i in range(1, 1000):
        an = -i * (i - a)
        b += 2
        d = an * d + b
        d = 1e-300 if abs(d) < 1e-300 else d
        c = b + an / c
        c = 1e-300 if abs(c) < 1e-300 else c
        d = 1 / d
        de = d * c
        h *= de
        if abs(de - 1) < 1e-15:
            break
    return math.exp(-x + a * math.log(x) - gln) * h


def main():
    g = R.MEGA_MILLIONS
    st = R.Stats(g, R.load_draws(os.path.join(ROOT, "data", "draws.csv"), g))
    D = st.D
    ew, eb = D * 5 / 70, D / 24
    chiw = sum((st.wf[n] - ew) ** 2 / ew for n in st.whites())
    chib = sum((st.bf[n] - eb) ** 2 / eb for n in st.bonuses())
    pw, pb = gammaq(69 / 2, chiw / 2), gammaq(23 / 2, chib / 2)
    L = []
    a = L.append
    a("# Mega Millions draw statistics (current matrix)")
    a("")
    a("> **Honest note.** Every draw is independent and every ticket is equally likely: "
      "**1 in 290,472,336**. Hot/cold/overdue analysis is for fun and cannot predict results. "
      "Weighted picks are not uniform, so plain uniform-random (`pick --mode uniform`) stays the default.")
    a("")
    a("Generated by `tools/make_stats_md.py` from `data/draws.csv` (source: NY Open Data, "
      "`https://data.ny.gov/api/views/5xaw-6ayf/rows.csv?accessType=DOWNLOAD`). "
      "The exact CLI output for the same data is `tests/golden/stats.txt`.")
    a("")
    a("| Item | Value |")
    a("|---|---|")
    a("| Matrix | 5 white balls of 1-70 + Mega Ball 1-24 (from 2025-04-08) |")
    a("| Draws | %d |" % D)
    a("| Date range | %s to %s |" % (st.draws[0][0], st.draws[-1][0]))
    a("| Expected hits per white ball | %d x 5 / 70 = %.2f |" % (D, ew))
    a("| Expected hits per Mega Ball | %d / 24 = %.2f |" % (D, eb))
    a("")
    a("\"Gap\" = draws since the number last appeared (0 = in the most recent draw; "
      "never drawn = %d). Rankings follow SPEC.md section 5." % D)
    a("")
    for title, pool, top in (("White balls", "w", 10), ("Mega Ball", "b", 5)):
        f = st.wf if pool == "w" else st.bf
        gap = st.wgap if pool == "w" else st.bgap
        e = ew if pool == "w" else eb
        a("## %s" % title)
        a("")
        for kind, label in (("hot", "Hot (most drawn)"), ("cold", "Cold (least drawn)"),
                            ("overdue", "Overdue (longest gap)")):
            a("**%s, top %d**" % (label, top))
            a("")
            a("| Rank | Number | Freq | vs expected | Gap |")
            a("|---:|---:|---:|---:|---:|")
            for r, n in enumerate(st.rank(kind, pool)[:top], 1):
                a("| %d | %02d | %d | %+.2f | %d |" % (r, n, f[n], f[n] - e, gap[n]))
            a("")
    a("## Chi-square goodness of fit vs uniform")
    a("")
    a("| Pool | chi-square | df | p-value (approx.) |")
    a("|---|---:|---:|---:|")
    a("| White balls (845 ball draws over 70 numbers) | %.2f | 69 | %.3f |" % (chiw, pw))
    a("| Mega Ball (169 draws over 24 numbers) | %.2f | 23 | %.3f |" % (chib, pb))
    a("")
    a("p-value = P(chi-square >= observed) under a fair, uniform draw, computed with the regularized "
      "upper incomplete gamma function Q(df/2, x/2). Note: the 5 whites in a draw are sampled without "
      "replacement, so the white-ball test is a close approximation, not exact.")
    a("")
    concl = []
    for nm, p in (("white balls", pw), ("Mega Balls", pb)):
        concl.append("the %s give p = %.2f, %s" % (
            nm, p, "far above 0.05, so there is no evidence of bias" if p > 0.05
            else "below 0.05; with this few draws treat it as noise unless it persists"))
    a("**Plain-language conclusion:** %s; %s. The spread between \"hot\" and \"cold\" numbers is "
      "about what pure chance produces with only %d draws (roughly 12 hits per white ball and 7 per "
      "Mega Ball). Nothing here suggests the draws are anything but uniform random." % (concl[0], concl[1], D))
    a("")
    a("## The 3 deterministic guess tickets (`mega-index guess`)")
    a("")
    a("| Play | Kind | Ticket | Index |")
    a("|---|---|---|---:|")
    for letter, (label, w, b, i) in zip("ABC", R.guess_tickets(st)):
        a("| %s | %s | %s | %s |" % (letter, label, R.fmt_ticket(g, w, b), R.group(i)))
    a("")
    a("- HOT = top 5 hot whites + top hot Mega Ball.")
    a("- COLD = top 5 cold whites + top cold Mega Ball.")
    a("- BALANCED = top 3 hot whites + the 2 most overdue whites not already chosen + the most overdue Mega Ball.")
    a("")
    a("> These guesses have exactly the same odds as any other ticket: **1 in 290,472,336**. For fun only.")
    a("")
    with open(os.path.join(ROOT, "docs", "STATS.md"), "w", newline="\n") as fh:
        fh.write("\n".join(L))
    print("chi white %.2f p=%.3f; chi MB %.2f p=%.3f" % (chiw, pw, chib, pb))


if __name__ == "__main__":
    main()
