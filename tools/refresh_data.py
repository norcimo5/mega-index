#!/usr/bin/env python3
"""Refresh Mega Millions draw history (stdlib only).

Downloads the NY Open Data CSV (or uses the saved raw copy with --offline),
filters to the current matrix (draws on/after 2025-04-08: 5 of 1-70 + MB 1-24),
validates, sorts, and writes:
  data/draws.csv              canonical file read by every CLI
  src/web/js/draws-data.js    plain script (window.MM_DRAWS) for the web app

Usage: python3 tools/refresh_data.py [--offline]
"""
import csv
import io
import json
import os
import sys
import urllib.request
from datetime import datetime, timezone

URL = "https://data.ny.gov/api/views/5xaw-6ayf/rows.csv?accessType=DOWNLOAD"
MATRIX_START = "2025-04-08"
WHITE_COUNT, WHITE_MAX, BONUS_MAX = 5, 70, 24

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "data", "mega-millions-ny-opendata-raw.csv")
DRAWS = os.path.join(ROOT, "data", "draws.csv")
JS = os.path.join(ROOT, "src", "web", "js", "draws-data.js")


def fail(msg):
    print("error: " + msg, file=sys.stderr)
    sys.exit(1)


def load_raw(offline):
    if offline:
        if not os.path.exists(RAW):
            fail("raw CSV not found: " + RAW)
        with open(RAW, "rb") as fh:
            return fh.read().decode("utf-8-sig")
    req = urllib.request.Request(URL, headers={"User-Agent": "mega-index-refresh/1.0"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        data = resp.read()
    text = data.decode("utf-8-sig")
    if "Draw Date" not in text.splitlines()[0]:
        fail("unexpected download format (no 'Draw Date' header)")
    with open(RAW, "wb") as fh:
        fh.write(data)
    return text


def parse(text):
    draws = {}
    for row in csv.DictReader(io.StringIO(text)):
        m, d, y = row["Draw Date"].strip().split("/")
        iso = "%04d-%02d-%02d" % (int(y), int(m), int(d))
        if iso < MATRIX_START:
            continue
        whites = sorted(int(x) for x in row["Winning Numbers"].split())
        mb = int(row["Mega Ball"])
        if len(whites) != WHITE_COUNT or len(set(whites)) != WHITE_COUNT:
            fail("%s: need %d distinct white balls, got %r" % (iso, WHITE_COUNT, whites))
        if not all(1 <= w <= WHITE_MAX for w in whites):
            fail("%s: white ball out of range 1-%d: %r" % (iso, WHITE_MAX, whites))
        if not 1 <= mb <= BONUS_MAX:
            fail("%s: Mega Ball out of range 1-%d: %d" % (iso, BONUS_MAX, mb))
        rec = (whites, mb)
        if iso in draws and draws[iso] != rec:
            fail("%s: conflicting duplicate rows" % iso)
        draws[iso] = rec
    if not draws:
        fail("no draws on/after " + MATRIX_START)
    return sorted((d, w, m) for d, (w, m) in draws.items())


def main(argv):
    offline = "--offline" in argv
    if any(a not in ("--offline",) for a in argv):
        if "-h" in argv or "--help" in argv:
            print(__doc__)
            return 0
        fail("usage: refresh_data.py [--offline]")
    draws = parse(load_raw(offline))
    os.makedirs(os.path.dirname(DRAWS), exist_ok=True)
    with open(DRAWS, "w", newline="\n") as fh:
        fh.write("date,w1,w2,w3,w4,w5,mb\n")
        for d, w, m in draws:
            fh.write("%s,%s,%d\n" % (d, ",".join(str(x) for x in w), m))
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    os.makedirs(os.path.dirname(JS), exist_ok=True)
    with open(JS, "w", newline="\n") as fh:
        fh.write("/* Generated by tools/refresh_data.py - do not edit. Plain script, no module. */\n")
        fh.write("window.MM_DRAWS = [\n")
        fh.write(",\n".join(json.dumps({"d": d, "w": w, "m": m}, separators=(",", ":")) for d, w, m in draws))
        fh.write("\n];\n")
        fh.write('window.MM_DRAWS_UPDATED = "%s";\n' % stamp)
    print("draws: %d (%s .. %s)" % (len(draws), draws[0][0], draws[-1][0]))
    print("wrote " + os.path.relpath(DRAWS, ROOT))
    print("wrote " + os.path.relpath(JS, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
